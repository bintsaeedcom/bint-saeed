function placeDiscoveryTerms(place: string): string[] {
  const p = place.trim()
  const variants = [p, p.replace(/\s+/g, '')]
  const suffixes = [
    'fashion',
    'style',
    'outfit',
    'shop',
    'beauty',
    'jewellery',
    'jewelry',
    'abaya',
    'dress',
    'ladies wear',
    'ladies',
    'mkhawer',
    'mkhawer fashion',
  ]
  const terms: string[] = []
  for (const v of variants) {
    for (const s of suffixes) {
      terms.push(`${v} ${s}`)
    }
  }
  return terms
}

