function dedupe(list: readonly string[]): string[] {
  const seen = new Set<string>()
  const out: string[] = []
  for (const raw of list) {
    const k = raw.trim()
    if (!k) continue
    const lower = k.toLowerCase()
    if (seen.has(lower)) continue
    seen.add(lower)
    out.push(k)
  }
  return out
}

function outfitSetPairs(outfits: readonly string[]): string[] {
  return outfits.flatMap((phrase) => {
    const setPhrase = phrase.replace(/\boutfit\b/gi, 'set')
    return setPhrase.toLowerCase() !== phrase.toLowerCase() ? [phrase, setPhrase] : [phrase]
  })
}

