function resolveLocale(locale: AppLocale | string): AppLocale {
  if (locale in CARE_BY_LOCALE) return locale as AppLocale
  throw new Error(`Missing jewellery care for locale: ${locale}`)
}

function pack(locale: AppLocale | string): CarePack {
  return CARE_BY_LOCALE[resolveLocale(locale)]
}

export function getJewelleryCareCopy(locale: AppLocale | string): {
  lead: string
  bullets: readonly string[]
} {
  const p = pack(locale)
  return { lead: p.lead, bullets: p.bullets }
}

export function getJewelleryCareFaqNecklace(locale: AppLocale | string): string {
  return pack(locale).faqNecklace
}

export function getJewelleryCareFaqEarring(locale: AppLocale | string): string {
  return pack(locale).faqEarring
}

export function getStrandCareBullets(locale: AppLocale | string): readonly string[] {
  return pack(locale).strand
}

export function getStrandSchemaCare(locale: AppLocale | string): string {
  return pack(locale).strandSchema
}

export function getAccessoryCareBullets(locale: AppLocale | string): readonly string[] {
  return pack(locale).accessory
}
