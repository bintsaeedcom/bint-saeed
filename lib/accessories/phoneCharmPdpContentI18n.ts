const ID_TO_STONE_KEY: Record<AlQuaaPhoneCharmId, string> = {
  'al-quaa-phone-charm-fuchsia-jade': 'fuchsia-jade',
  'al-quaa-phone-charm-orange-jade': 'orange-jade',
  'al-quaa-phone-charm-onyx': 'onyx',
  'al-quaa-phone-charm-tiger-eye': 'tiger-eye',
  'al-quaa-phone-charm-malachite': 'malachite',
  'al-quaa-phone-charm-lapis-lazuli': 'lapis-lazuli',
  'al-quaa-phone-charm-rose-quartz': 'rose-quartz',
}

export function buildPhoneCharmPdpPack(
  id: AlQuaaPhoneCharmId,
  locale: AppLocale,
): PhoneCharmPdpContentPack {
  const stoneKey = ID_TO_STONE_KEY[id]
  const stone = STONE_BY_LOCALE[locale][stoneKey] ?? STONE_BY_LOCALE.en[stoneKey]
  const t = TEMPLATES[locale] ?? TEMPLATES.en
  const labels = getPhoneCharmSectionLabels(locale)
  const jewelleryCare = getJewelleryCareCopy(locale)
  const useSharedJewelleryCare = locale === 'en' || locale === 'ar' || locale === 'fr'
  const careBullets = useSharedJewelleryCare ? [...jewelleryCare.bullets] : t.care
  const careLead = useSharedJewelleryCare ? jewelleryCare.lead : ''
  const careFaqAnswer = useSharedJewelleryCare
    ? `${jewelleryCare.lead} ${careBullets.join(' ')}`
    : careBullets.join(' ')

  const features = [
    t.houseCode,
    t.craftedIn,
    t.handAssembled,
    t.length,
    t.decorative,
    t.cord,
    t.beadLine(stone.stoneLabel),
    t.rosetteLine,
    t.hematite,
    t.variation,
    t.compat1,
    t.compat2,
    t.colourLine(stone.stoneLabel),
  ]

  return {
    headline: t.headline(stone.stoneLabel),
    introParagraphs: t.introParagraphs(stone.stoneLabel, stone.beadPhrase, stone.characterLead),
    featuresTitle: labels.featuresTitle,
    features,
    careLead,
    care: careBullets,
    colour: stone.stoneLabel,
    faq: [
      { question: t.faqNaturalQ, answer: t.faqNaturalA },
      { question: t.faqRosetteQ, answer: t.faqRosetteA },
      { question: t.faqCareQ, answer: careFaqAnswer },
    ],
  }
}
