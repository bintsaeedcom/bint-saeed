function localeKey(locale: AppLocale | string): AppLocale {
  return locale in CATEGORY_NAME ? (locale as AppLocale) : 'en'
}

export function getAccessoryCategoryName(
  locale: AppLocale | string,
  categoryId: string,
  fallbackEn?: string,
  fallbackAr?: string,
): string {
  const key = localeKey(locale)
  const mapped = CATEGORY_NAME[key][categoryId as AccessoryCategoryId]
  if (mapped) return mapped
  if (key === 'ar' && fallbackAr) return fallbackAr
  return fallbackEn ?? categoryId
}

export function getAccessoryCategoryDescription(
  locale: AppLocale | string,
  categoryId: string,
  fallbackEn?: string,
  fallbackAr?: string,
): string | undefined {
  const key = localeKey(locale)
  const pack = CATEGORY_DESC[categoryId as AccessoryCategoryId]
  if (pack?.[key]) return pack[key]
  if (key === 'ar' && fallbackAr) return fallbackAr
  return fallbackEn
}

