export function getGiftCardsPageCopy(locale: AppLocale | string): GiftCardsPageCopy {
  const key = (locale in BY_LOCALE ? locale : 'en') as AppLocale
  return BY_LOCALE[key]
}

export function formatGiftCardLineName(locale: AppLocale | string, amountLabel: string): string {
  const copy = getGiftCardsPageCopy(locale)
  return copy.cardNamePrefix.replace('{amount}', amountLabel)
}
