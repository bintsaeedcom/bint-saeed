export function isCoventGardenAbayaPageSlug(slug: string): boolean {
  return slug.toLowerCase() === COVENT_GARDEN_ABAYA_SLUG
}

export function getCoventGardenAbayaPageSeo(
  slug: string,
  locale: AppLocale = 'en',
): { title: string; description: string } | null {
  if (!isCoventGardenAbayaPageSlug(slug)) return null
  const pack = PAGE_SEO[locale] ?? PAGE_SEO.en
  return { title: pack.pageTitle, description: pack.metaDescription }
}

/** Meta + schema keyword list — all 12 locales, no English fallback. */
export function getCoventGardenAbayaMetaKeywordTerms(
  locale: AppLocale = 'en',
  colorName?: string,
): string[] {
  const terms = new Set<string>([
    ...(META_KEYWORDS[locale] ?? META_KEYWORDS.en),
    ...(EXTRA_META_KEYWORDS[locale] ?? []),
  ])
  const color = colorName?.trim()
  if (color) {
    terms.add(color)
    terms.add(`${color} ${ABAYA_TYPE[locale]}`)
    terms.add(`${G[locale].city} ${ABAYA_TYPE[locale]} ${color}`)
  }
  return [...terms]
}

export function getCoventGardenAbayaMetaKeywords(
  locale: AppLocale = 'en',
  colorName?: string,
): string {
  return getCoventGardenAbayaMetaKeywordTerms(locale, colorName).join(', ')
}
