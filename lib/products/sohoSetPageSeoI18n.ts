export function isSohoSetPageSlug(slug: string): boolean {
  return slug.toLowerCase() === SOHO_SET_SLUG
}

export function getSohoSetPageSeo(
  slug: string,
  locale: AppLocale = 'en',
): { title: string; description: string } | null {
  if (!isSohoSetPageSlug(slug)) return null
  const pack = PAGE_SEO[locale] ?? PAGE_SEO.en
  return { title: pack.pageTitle, description: pack.metaDescription }
}

export function getSohoSetMetaKeywordTerms(
  locale: AppLocale = 'en',
  colorName?: string,
): string[] {
  const terms = new Set<string>([
    ...(META_KEYWORDS[locale] ?? META_KEYWORDS.en),
    ...getSohoSetSchemaKeywordExpansion(locale),
  ])
  const color = colorName?.trim()
  if (color) {
    terms.add(color)
    terms.add(`${color} ${SET_TYPE[locale]}`)
    terms.add(`${G[locale].city} ${SET_TYPE[locale]} ${color}`)
    terms.add(`Soho Set ${color}`)
    terms.add(`${color} outfit`)
    terms.add(`${color} set`)
  }
  return [...terms]
}

export function getSohoSetMetaKeywords(
  locale: AppLocale = 'en',
  colorName?: string,
): string {
  return getSohoSetMetaKeywordTerms(locale, colorName).join(', ')
}
